import {
  BadRequestException,
  Body,
  ConflictException,
  Controller,
  Get,
  NotFoundException,
  Param,
  ParseUUIDPipe,
  Post,
  Query,
} from '@nestjs/common';
import { schema } from '@pos/db';
import { and, asc, desc, eq, inArray, isNull, sql } from 'drizzle-orm';
import { z } from 'zod';
import { Db } from '../core/database';
import { RequireModule, RequirePermission } from '../core/decorators';
import { Events } from '../core/events';
import { currentContext, currentTenant, currentUserId } from '../core/request-context';
import { ZodPipe } from '../core/zod';
import { LedgerService } from './ledger.service';

type Status = 'open' | 'submitted' | 'approved' | 'cancelled';

const createBody = z.object({
  locationId: z.string().uuid(),
  name: z.string().trim().min(1).max(100),
});

const entriesBody = z.object({
  entries: z
    .array(
      z.object({
        /** Generated by the client; resending the same id is a no-op. */
        id: z.string().uuid(),
        variantId: z.string().uuid(),
        quantity: z.number().int().min(1).max(1_000_000),
        /** When the item was counted on the device. Defaults to now. */
        countedAt: z.coerce.date().optional(),
      }),
    )
    .min(1)
    .max(500),
});

const listQuery = z.object({
  status: z.enum(['open', 'submitted', 'approved', 'cancelled']).optional(),
  locationId: z.string().uuid().optional(),
  limit: z.coerce.number().int().min(1).max(100).default(50),
});

/** Allowed clock drift for device-supplied count times. */
const MAX_FUTURE_MS = 5 * 60_000;

export interface CountLine {
  variantId: string;
  productName: string;
  variantName: string;
  sku: string | null;
  counted: number;
  countedAt: string;
  /** Ledger balance at this location as of countedAt. */
  expected: number;
  discrepancy: number;
  onHandNow: number;
}

@Controller('inventory/counts')
@RequireModule('inventory')
export class CountsController {
  constructor(
    private readonly db: Db,
    private readonly ledger: LedgerService,
    private readonly events: Events,
  ) {}

  @RequirePermission('inventory.read')
  @Get()
  async list(@Query(new ZodPipe(listQuery)) q: z.infer<typeof listQuery>) {
    const s = schema.countSessions;
    return this.db.tx
      .select({
        id: s.id,
        name: s.name,
        status: s.status,
        locationId: s.locationId,
        locationName: schema.locations.name,
        startedAt: s.startedAt,
        submittedAt: s.submittedAt,
        closedAt: s.closedAt,
        entryCount: sql<number>`(select count(*) from count_entries e where e.session_id = count_sessions.id and e.voided_at is null)`.mapWith(Number),
      })
      .from(s)
      .innerJoin(schema.locations, eq(schema.locations.id, s.locationId))
      .where(and(q.status ? eq(s.status, q.status) : undefined, q.locationId ? eq(s.locationId, q.locationId) : undefined))
      .orderBy(desc(s.startedAt))
      .limit(q.limit);
  }

  @RequirePermission('inventory.count')
  @Post()
  async create(@Body(new ZodPipe(createBody)) body: z.infer<typeof createBody>) {
    const [location] = await this.db.tx
      .select({ id: schema.locations.id })
      .from(schema.locations)
      .where(and(eq(schema.locations.id, body.locationId), isNull(schema.locations.archivedAt)));
    if (!location) throw new NotFoundException('Location not found or archived');
    const [session] = await this.db.tx
      .insert(schema.countSessions)
      .values({ tenantId: currentTenant().tenantId, ...body, startedBy: currentUserId() })
      .returning();
    await this.events.record('count.started', { type: 'count', id: session!.id }, body);
    return session;
  }

  /** The session with each counted item compared against the ledger. */
  @RequirePermission('inventory.read')
  @Get(':id')
  async get(@Param('id', ParseUUIDPipe) id: string) {
    const session = await this.find(id);
    const lines = await this.review(session.id, session.locationId);
    return {
      ...session,
      lines,
      totals: {
        items: lines.length,
        withDiscrepancy: lines.filter((l) => l.discrepancy !== 0).length,
        netUnits: lines.reduce((sum, l) => sum + l.discrepancy, 0),
      },
    };
  }

  @RequirePermission('inventory.read')
  @Get(':id/entries')
  async entries(@Param('id', ParseUUIDPipe) id: string) {
    await this.find(id);
    const e = schema.countEntries;
    return this.db.tx
      .select({
        id: e.id,
        variantId: e.variantId,
        variantName: schema.productVariants.name,
        productName: schema.products.name,
        quantity: e.quantity,
        countedAt: e.countedAt,
        voidedAt: e.voidedAt,
        countedBy: { email: schema.users.email, displayName: schema.users.displayName },
      })
      .from(e)
      .innerJoin(schema.productVariants, eq(schema.productVariants.id, e.variantId))
      .innerJoin(schema.products, eq(schema.products.id, schema.productVariants.productId))
      .leftJoin(schema.users, eq(schema.users.id, e.countedBy))
      .where(eq(e.sessionId, id))
      .orderBy(desc(e.countedAt), desc(e.createdAt));
  }

  @RequirePermission('inventory.count')
  @Post(':id/entries')
  async addEntries(@Param('id', ParseUUIDPipe) id: string, @Body(new ZodPipe(entriesBody)) body: z.infer<typeof entriesBody>) {
    const session = await this.lock(id, ['open']);
    const variantIds = [...new Set(body.entries.map((e) => e.variantId))];
    const variants = await this.db.tx
      .select({ id: schema.productVariants.id, track: schema.productVariants.trackInventory })
      .from(schema.productVariants)
      .where(inArray(schema.productVariants.id, variantIds));
    if (variants.length !== variantIds.length) throw new NotFoundException('Product variant not found');
    if (variants.some((v) => !v.track)) throw new BadRequestException('Inventory is not tracked for one of these items');

    const now = Date.now();
    const rows = body.entries.map((e) => {
      const at = e.countedAt?.getTime() ?? now;
      if (at > now + MAX_FUTURE_MS) throw new BadRequestException('countedAt is in the future');
      return {
        id: e.id,
        tenantId: session.tenantId,
        sessionId: id,
        variantId: e.variantId,
        quantity: e.quantity,
        // Entries can't predate the session they belong to.
        countedAt: new Date(Math.max(Math.min(at, now), session.startedAt.getTime())),
        countedBy: currentUserId(),
        deviceId: currentContext().device?.id ?? null,
      };
    });
    const inserted = await this.db.tx
      .insert(schema.countEntries)
      .values(rows)
      .onConflictDoNothing({ target: schema.countEntries.id })
      .returning({ id: schema.countEntries.id, sessionId: schema.countEntries.sessionId });
    // An id reused for a different session is a client bug, not a retry.
    const existing = rows.filter((r) => !inserted.some((i) => i.id === r.id)).map((r) => r.id);
    if (existing.length) {
      const clash = await this.db.tx
        .select({ id: schema.countEntries.id })
        .from(schema.countEntries)
        .where(and(inArray(schema.countEntries.id, existing), sql`${schema.countEntries.sessionId} <> ${id}`));
      if (clash.length) throw new ConflictException('Entry id already used in another count');
    }
    return { accepted: inserted.length, duplicates: existing.length };
  }

  @RequirePermission('inventory.count')
  @Post(':id/entries/:entryId/void')
  async voidEntry(@Param('id', ParseUUIDPipe) id: string, @Param('entryId', ParseUUIDPipe) entryId: string) {
    await this.lock(id, ['open']);
    const [entry] = await this.db.tx
      .update(schema.countEntries)
      .set({ voidedAt: new Date(), voidedBy: currentUserId() })
      .where(and(eq(schema.countEntries.id, entryId), eq(schema.countEntries.sessionId, id), isNull(schema.countEntries.voidedAt)))
      .returning({ id: schema.countEntries.id });
    if (!entry) throw new NotFoundException('Entry not found or already voided');
    return { id: entryId, voided: true };
  }

  @RequirePermission('inventory.count')
  @Post(':id/submit')
  async submit(@Param('id', ParseUUIDPipe) id: string) {
    await this.lock(id, ['open']);
    const [{ n }] = (await this.db.tx
      .select({ n: sql<number>`count(*)`.mapWith(Number) })
      .from(schema.countEntries)
      .where(and(eq(schema.countEntries.sessionId, id), isNull(schema.countEntries.voidedAt)))) as [{ n: number }];
    if (n === 0) throw new BadRequestException('Count at least one item before submitting');
    await this.transition(id, 'submitted', { submittedAt: new Date(), submittedBy: currentUserId() });
    await this.events.record('count.submitted', { type: 'count', id });
    return this.get(id);
  }

  @RequirePermission('inventory.count')
  @Post(':id/reopen')
  async reopen(@Param('id', ParseUUIDPipe) id: string) {
    await this.lock(id, ['submitted']);
    await this.transition(id, 'open', { submittedAt: null, submittedBy: null });
    await this.events.record('count.reopened', { type: 'count', id });
    return this.get(id);
  }

  @RequirePermission('inventory.count')
  @Post(':id/cancel')
  async cancel(@Param('id', ParseUUIDPipe) id: string) {
    await this.lock(id, ['open', 'submitted']);
    await this.transition(id, 'cancelled', { closedAt: new Date(), closedBy: currentUserId() });
    await this.events.record('count.cancelled', { type: 'count', id });
    return this.get(id);
  }

  /** Posts a count_adjustment movement for every item whose count differs from the ledger. */
  @RequirePermission('inventory.count.approve')
  @Post(':id/approve')
  async approve(@Param('id', ParseUUIDPipe) id: string) {
    const session = await this.lock(id, ['submitted']);
    const lines = await this.review(id, session.locationId);
    const changes = lines.filter((l) => l.discrepancy !== 0);

    let operationId: string | null = null;
    if (changes.length) {
      const result = await this.ledger.record({
        kind: 'count',
        note: `Count: ${session.name}`,
        reference: { type: 'count', id },
        lines: changes.map((l) => ({
          locationId: session.locationId,
          variantId: l.variantId,
          quantityDelta: l.discrepancy,
          reason: 'count_adjustment',
        })),
      });
      operationId = result.operationId;
    }
    await this.transition(id, 'approved', { closedAt: new Date(), closedBy: currentUserId(), operationId });
    await this.events.record('count.approved', { type: 'count', id }, {
      locationId: session.locationId,
      adjustments: changes.map((l) => ({ variantId: l.variantId, quantityDelta: l.discrepancy })),
    });
    return this.get(id);
  }

  /**
   * Compares each counted variant with the ledger balance at the moment it was
   * last counted, so sales or receipts during the count are not treated as
   * discrepancies.
   */
  private async review(sessionId: string, locationId: string): Promise<CountLine[]> {
    const rows = await this.db.tx.execute<{
      variant_id: string;
      product_name: string;
      variant_name: string;
      sku: string | null;
      counted: string;
      counted_at: Date | string;
      expected: string;
      on_hand_now: string | null;
    }>(sql`
      with counted as (
        select variant_id, sum(quantity) as counted, max(counted_at) as counted_at
        from count_entries
        where session_id = ${sessionId} and voided_at is null
        group by variant_id
      )
      select c.variant_id, p.name as product_name, v.name as variant_name, v.sku,
             c.counted, c.counted_at,
             coalesce((
               select sum(m.quantity_delta) from stock_movements m
               where m.location_id = ${locationId} and m.variant_id = c.variant_id
                 and m.occurred_at <= c.counted_at
                 and m.reference_id is distinct from ${sessionId}
             ), 0) as expected,
             l.on_hand as on_hand_now
      from counted c
      join product_variants v on v.id = c.variant_id
      join products p on p.id = v.product_id
      left join stock_levels l on l.location_id = ${locationId} and l.variant_id = c.variant_id
      order by lower(p.name), v.position, v.id
    `);
    return rows.map((r) => {
      const counted = Number(r.counted);
      const expected = Number(r.expected);
      return {
        variantId: r.variant_id,
        productName: r.product_name,
        variantName: r.variant_name,
        sku: r.sku,
        counted,
        countedAt: new Date(r.counted_at).toISOString(),
        expected,
        discrepancy: counted - expected,
        onHandNow: Number(r.on_hand_now ?? 0),
      };
    });
  }

  private async find(id: string) {
    const [session] = await this.db.tx.select().from(schema.countSessions).where(eq(schema.countSessions.id, id));
    if (!session) throw new NotFoundException('Count not found');
    return session;
  }

  /** Locks the session row for this transaction and checks its status. */
  private async lock(id: string, allowed: Status[]) {
    const [session] = await this.db.tx.select().from(schema.countSessions).where(eq(schema.countSessions.id, id)).for('update');
    if (!session) throw new NotFoundException('Count not found');
    if (!allowed.includes(session.status)) {
      throw new ConflictException(`This count is ${session.status}; expected ${allowed.join(' or ')}`);
    }
    return session;
  }

  private async transition(id: string, status: Status, fields: Partial<typeof schema.countSessions.$inferInsert>) {
    await this.db.tx.update(schema.countSessions).set({ status, ...fields }).where(eq(schema.countSessions.id, id));
  }
}
